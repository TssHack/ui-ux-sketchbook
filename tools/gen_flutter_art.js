// Generate the Flutter illustration library from the plain-JS one, so both builds
// always draw the same thing. Usage: node tools/gen_flutter_art.js
// CI runs it and fails if the committed Dart file is out of date.
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const skill = path.join(root, "skills", "ui-ux-sketchbook", "assets");
const out = path.join(skill, "flutter", "lib", "src", "art_library.dart");

// Minimal browser stand-ins: the library only needs them to register itself.
const sandbox = {
  window: {},
  document: { readyState: "loading", addEventListener() {} },
  MutationObserver: class { observe() {} },
  console,
};
vm.createContext(sandbox);
for (const f of ["vanilla/sketchbook.js", "vanilla/art-library.js"]) {
  vm.runInContext(fs.readFileSync(path.join(skill, f), "utf8"), sandbox, { filename: f });
}
const art = sandbox.window.Sketchbook.art;

const color = (hex) => {
  let h = hex.replace("#", "");
  if (h.length === 3) h = [...h].map((c) => c + c).join("");
  if (!/^[0-9a-f]{6}$/i.test(h)) throw new Error(`Unsupported colour ${hex}`);
  return `Color(0xFF${h.toUpperCase()})`;
};
const str = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;
const num = (n) => (Number.isInteger(n) ? `${n}` : `${+n.toFixed(4)}`);

// Lettering that the web build draws as SVG <text> in `extra`.
const labels = { choco: "SketchLabel('Lotus', x: 56, y: 108, size: 25, rotate: -6, fontFamily: 'GochiHand')" };

const lines = [];
lines.push("// GENERATED by tools/gen_flutter_art.js from assets/vanilla/art-library.js. Do not edit by hand.");
lines.push("import 'dart:ui';");
lines.push("");
lines.push("import 'drawing.dart';");
lines.push("");
lines.push("/// The ready illustrations, by name: " + Object.keys(art).join(", ") + ".");
lines.push("const Map<String, DrawingSpec> sketchArt = {");
for (const [name, spec] of Object.entries(art)) {
  const [x, y, w, h] = spec.viewBox.split(/\s+/).map(Number);
  lines.push(`  ${str(name)}: DrawingSpec(`);
  lines.push(`    viewBox: Rect.fromLTWH(${num(x)}, ${num(y)}, ${num(w)}, ${num(h)}),`);
  lines.push("    shapes: [");
  for (const s of spec.shapes) {
    const args = [str(s.d)];
    if (s.fill) args.push(`fill: ${color(s.fill)}`);
    if (s.shade) args.push(`shade: ${color(s.shade)}`);
    if (s.shadeWidth !== undefined) args.push(`shadeWidth: ${num(s.shadeWidth)}`);
    if (s.ink !== undefined) args.push(`ink: ${num(s.ink)}`);
    if (s.inkColor) args.push(`inkColor: ${color(s.inkColor)}`);
    if (s.transform) args.push(`transform: ${str(s.transform)}`);
    lines.push(`      DrawingShape(${args.join(", ")}),`);
  }
  lines.push("    ],");
  if (labels[name]) lines.push(`    labels: [${labels[name]}],`);
  else if (spec.extra) throw new Error(`${name} has extra SVG; add a SketchLabel for it in gen_flutter_art.js`);
  lines.push("  ),");
}
lines.push("};");
lines.push("");

fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(root, out)}: ${Object.keys(art).length} illustrations`);
